#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn predefined_tables_match_annex_d() {
        assert_eq!(win_ansi(0xE9), Some("eacute"));
        assert_eq!(standard(0x27), Some("quoteright"));
        assert_eq!(standard(0x60), Some("quoteleft"));
        assert_eq!(win_ansi(0x27), Some("quotesingle"));
        assert_eq!(symbol(0x61), Some("alpha"));
        assert_eq!(symbol(0x53), Some("Sigma"));
        assert_eq!(zapf_dingbats(0x21), Some("a1"));
        assert_eq!(zapf_dingbats(0xFE), Some("a191"));
        assert_eq!(mac_roman(0xCA), Some("space"));
        assert_eq!(mac_roman(0x8E), Some("eacute"));
        assert_eq!(mac_expert(0x61), Some("Asmall"));
        assert_eq!(pdf_doc(0xA0), Some("Euro"));
        assert_eq!(pdf_doc(0x18), Some("breve"));
        assert_eq!(standard(0xFF), None);
        assert_eq!(standard(0x00), None);
    }

    #[test]
    fn win_ansi_notes() {
        // Note 3 : codes libres au-dessus de 127 rendus comme bullet.
        assert_eq!(win_ansi(0x81), Some("bullet"));
        assert_eq!(win_ansi(0x9D), Some("bullet"));
        // Note 5 : 173 est hyphen ; note 6 : 160 est space.
        assert_eq!(win_ansi(0xAD), Some("hyphen"));
        assert_eq!(win_ansi(0xA0), Some("space"));
        assert_eq!(win_ansi(0x80), Some("Euro"));
    }

    #[test]
    fn base_encoding_names() {
        assert_eq!(
            BaseEncoding::from_pdf_name("WinAnsiEncoding"),
            Some(BaseEncoding::WinAnsi)
        );
        assert_eq!(BaseEncoding::from_pdf_name("Foo"), None);
        assert_eq!(BaseEncoding::MacRoman.lookup(0xA5), Some("bullet"));
        assert_eq!(BaseEncoding::ZapfDingbats.table()[0x20], Some("space"));
    }

    #[test]
    fn agl_lookup_and_rules() {
        assert_eq!(glyph_name_to_unicode("eacute"), Some('é'));
        assert_eq!(glyph_name_to_unicode("A"), Some('A'));
        assert_eq!(glyph_name_to_unicode("alpha"), Some('α'));
        assert_eq!(glyph_name_to_unicode("Euro"), Some('€'));
        assert_eq!(glyph_name_to_unicode("fi"), Some('\u{FB01}'));
        assert_eq!(glyph_name_to_unicode("afii10017"), Some('А'));
        assert_eq!(glyph_name_to_unicode("afii10071"), Some('ё'));
        assert_eq!(glyph_name_to_unicode("uni00E9"), Some('é'));
        assert_eq!(glyph_name_to_unicode("uni00E90301"), Some('é'));
        assert_eq!(glyph_name_to_unicode("u1F600"), Some('\u{1F600}'));
        assert_eq!(glyph_name_to_unicode("u00E9"), Some('é'));
        assert_eq!(glyph_name_to_unicode("a.sc"), Some('a'));
        assert_eq!(glyph_name_to_unicode("eacute.alt"), Some('é'));
        assert_eq!(glyph_name_to_unicode("f_f_i"), Some('f'));
        assert_eq!(glyph_name_to_unicode("g12"), None);
        assert_eq!(glyph_name_to_unicode("cid12"), None);
        assert_eq!(glyph_name_to_unicode("G12"), None);
        assert_eq!(glyph_name_to_unicode(""), None);
        assert_eq!(glyph_name_to_unicode(".notdef"), None);
        assert_eq!(glyph_name_to_unicode("uni00e9"), None);
        assert_eq!(glyph_name_to_unicode("uniD800"), None);
    }

    #[test]
    fn every_predefined_name_is_known_to_agl_except_dingbats() {
        for enc in [
            BaseEncoding::Standard,
            BaseEncoding::WinAnsi,
            BaseEncoding::MacRoman,
            BaseEncoding::MacExpert,
            BaseEncoding::PdfDoc,
            BaseEncoding::Symbol,
        ] {
            for name in enc.table().iter().flatten() {
                assert!(
                    glyph_name_to_unicode(name).is_some(),
                    "{name} absent de l'AGL réduite ({enc:?})"
                );
            }
        }
    }
}
