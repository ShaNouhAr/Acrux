//! Encodages prédéfinis des polices simples (ISO 32000-2 annexe D) et
//! correspondance nom de glyphe → Unicode (Adobe Glyph List réduite).
//!
//! Chaque encodage est une table de 256 entrées `code → nom de glyphe`.
//! Tables fournies :
//! - `StandardEncoding`, `WinAnsiEncoding`, `MacRomanEncoding`,
//!   `MacExpertEncoding` (annexe D.2, tableaux D.1 et D.4),
//! - `PDFDocEncoding` (annexe D.3, orientée code → nom, à l'inverse de la
//!   table Unicode de `acrux-document`),
//! - encodages intégrés des polices `Symbol` et `ZapfDingbats`
//!   (annexes D.5 et D.6).
//!
//! `MacRomanEncoding` est complété par les symboles mathématiques du
//! Mac OS Roman d'Apple (`notequal`, `infinity`…) : ils ne figurent pas dans
//! le tableau D.1 mais sont utiles pour la sous-table `cmap` (1,0) des
//! polices TrueType, qui utilise le même encodage.
//!
//! Piège : dans WinAnsiEncoding, les codes non affectés au-dessus de 127
//! doivent afficher `bullet` (annexe D, note 3) et le code 160 est un espace
//! insécable rendu comme `space` (note 6) ; le code 173 est `hyphen` (note 5).

use std::collections::HashMap;
use std::sync::OnceLock;

/// Table d'encodage : nom de glyphe par code (`None` si le code est libre).
pub type Table = [Option<&'static str>; 256];

/// Construit une table à partir de listes `(code, nom)` ; les listes
/// suivantes écrasent les précédentes (utile pour dériver un encodage
/// d'un autre).
const fn build(parts: &[&[(u8, &'static str)]]) -> Table {
    let mut table: Table = [None; 256];
    let mut i = 0;
    while i < parts.len() {
        let part = parts[i];
        let mut j = 0;
        while j < part.len() {
            let (code, name) = part[j];
            table[code as usize] = Some(name);
            j += 1;
        }
        i += 1;
    }
    table
}

