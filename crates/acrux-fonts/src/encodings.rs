/// Encodage de base d'une police simple (ISO 32000-2 §9.6.5, entrée
/// /BaseEncoding, et encodages intégrés des polices standard).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum BaseEncoding {
    /// StandardEncoding.
    Standard,
    /// WinAnsiEncoding.
    WinAnsi,
    /// MacRomanEncoding.
    MacRoman,
    /// MacExpertEncoding.
    MacExpert,
    /// PDFDocEncoding.
    PdfDoc,
    /// Encodage intégré de Symbol.
    Symbol,
    /// Encodage intégré de ZapfDingbats.
    ZapfDingbats,
}

impl BaseEncoding {
    /// Encodage désigné par un nom PDF (`/WinAnsiEncoding`…), sans la barre.
    #[must_use]
    pub fn from_pdf_name(name: &str) -> Option<Self> {
        match name {
            "StandardEncoding" => Some(Self::Standard),
            "WinAnsiEncoding" => Some(Self::WinAnsi),
            "MacRomanEncoding" => Some(Self::MacRoman),
            "MacExpertEncoding" => Some(Self::MacExpert),
            "PDFDocEncoding" => Some(Self::PdfDoc),
            _ => None,
        }
    }

    /// Table complète.
    #[must_use]
    pub fn table(self) -> &'static Table {
        match self {
            Self::Standard => &STANDARD_TABLE,
            Self::WinAnsi => &WIN_ANSI_TABLE,
            Self::MacRoman => &MAC_ROMAN_TABLE,
            Self::MacExpert => &MAC_EXPERT_TABLE,
            Self::PdfDoc => &PDF_DOC_TABLE,
            Self::Symbol => &SYMBOL_TABLE,
            Self::ZapfDingbats => &ZAPF_DINGBATS_TABLE,
        }
    }

    /// Nom de glyphe d'un code.
    #[must_use]
    pub fn lookup(self, code: u8) -> Option<&'static str> {
        self.table()[code as usize]
    }
}

/// Nom de glyphe → Unicode selon l'Adobe Glyph List (AGL), version réduite
/// aux noms courants, complétée par les règles de l'« AGL Specification » :
/// - `uniXXXX` (hexadécimal majuscule, 4 chiffres, seule la première valeur
///   d'une séquence est retenue) et `uXXXX` à `uXXXXXX` ;
/// - suffixe de variante (`.sc`, `.alt`, `.swash`…) ignoré ;
/// - ligature `a_b` : premier composant ;
/// - noms d'index (`g12`, `cid12`, `G12`, `glyph12`) : `None`, il n'y a pas
///   de sémantique Unicode.
#[must_use]
pub fn glyph_name_to_unicode(name: &str) -> Option<char> {
    let base = name.split('.').next().unwrap_or("");
    if base.is_empty() {
        return None;
    }
    let component = base.split('_').next().unwrap_or(base);
    if let Some(c) = agl().get(component) {
        return Some(*c);
    }
    if let Some(hex) = component.strip_prefix("uni") {
        if hex.len() >= 4 && hex.len() % 4 == 0 && hex.bytes().all(is_upper_hex) {
            return u32::from_str_radix(&hex[..4], 16)
                .ok()
                .and_then(char::from_u32);
        }
    }
    if let Some(hex) = component.strip_prefix('u') {
        if (4..=6).contains(&hex.len()) && hex.bytes().all(is_upper_hex) {
            return u32::from_str_radix(hex, 16).ok().and_then(char::from_u32);
        }
    }
    None
}

fn is_upper_hex(b: u8) -> bool {
    b.is_ascii_digit() || (b'A'..=b'F').contains(&b)
}

/// Table AGL réduite, construite une seule fois.
fn agl() -> &'static HashMap<&'static str, char> {
    static AGL: OnceLock<HashMap<&'static str, char>> = OnceLock::new();
    AGL.get_or_init(|| {
        let mut map = HashMap::with_capacity(AGL_ENTRIES.len() + 96);
        for &(name, code) in AGL_ENTRIES {
            if let Some(c) = char::from_u32(code) {
                map.insert(name, c);
            }
        }
        for &(name, code) in CYRILLIC_AFII {
            if let Some(c) = char::from_u32(code) {
                map.insert(name, c);
            }
        }
        map
    })
}

